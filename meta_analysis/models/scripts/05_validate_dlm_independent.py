"""Independent re-implementation check of the hydrous ferric oxide (HFO) surface calculations.

Why: USGS Example 8 (02_validate_usgs_ex8.py) shows that our engines reproduce the USGS reference output,
but it uses one sorbate (Zn) and Example 8's own constants. Here a separate, from-scratch Python
implementation of the Dzombak & Morel (1990) diffuse-layer model takes the aqueous activities and ionic
strength reported by PHREEQC and solves the surface equations on its own:

    n_i   = K_i * x_t * prod_j(a_j ** nu_ij) * exp(-z_i F psi / R T)      (each surface species i on site type t)
    S_t   = x_t + sum_i n_i                                              (site balance, strong and weak sites)
    sigma = F * sum_i z_i n_i / A                                        (surface charge, C/m2)
    sigma = sqrt(8000 eps_r eps_0 R T I) * sinh(F psi / 2 R T)           (Gouy-Chapman, as in D&M 1990)

The surface reactions and log K values are parsed from the same database text the production runs use
(minteq.v4.dat SURFACE_SPECIES plus the Mn(II) and carbonate reactions added in model_setup.py).
eps_r(T) from Malmberg & Maryott (1956): 87.740 - 0.40008 t + 9.398e-4 t^2 - 1.410e-6 t^3.

Test cases
  T1  Cd edge: Cd 1e-7 M, 0.1 M NaNO3, 1e-3 M Fe as HFO (0.089 g/L), 25 C, pH 4-10 (single sorbate)
  T2  phosphate edge: P 1e-5 M, same background (single sorbate)
  T3  the production soft-water case: all 12 trace elements + Ca, Mg, sulfate, carbonate, HFO 1 mg Fe/L,
      16 C, pH 6-9 set by CO2 (exact input generated by 03_run_hfo_model.py)
  T4  diagnostic only (PHREEQC): single-sorbate edges for all 12 elements under D&M standard laboratory
      conditions -> validation/dm_standard_conditions_edges.csv (pH50, local slope at pH 7)
Writes validation/dlm_independent_check.csv and prints the maximum relative differences and pH50 values.
"""
import importlib.util
import os
import re
import sys

import numpy as np
import pandas as pd
from scipy.optimize import brentq

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from engine import Engine, db_path  # noqa: E402
import model_setup as M  # noqa: E402

spec = importlib.util.spec_from_file_location("run_hfo", os.path.join(HERE, "03_run_hfo_model.py"))
run_hfo = importlib.util.module_from_spec(spec)
spec.loader.exec_module(run_hfo)

F = 96485.33212
R = 8.314462618
EPS0 = 8.8541878128e-12
ROOT = M.ROOT
OUT = os.path.join(ROOT, "validation", "dlm_independent_check.csv")


def eps_r(t_c):
    return 87.740 - 0.40008 * t_c + 9.398e-4 * t_c ** 2 - 1.410e-6 * t_c ** 3


# ----------------------------------------------------------------------------- parse surface reactions
TOKEN = re.compile(r"^\s*([0-9.]*)\s*(\S+)\s*$")


def split_side(side):
    out = []
    for term in re.split(r"\s\+\s", " " + side.strip() + " "):
        term = term.strip()
        if not term:
            continue
        m = TOKEN.match(term)
        coef = float(m.group(1)) if m.group(1) else 1.0
        out.append((m.group(2), coef))
    return out


def charge_of(name):
    m = re.search(r"([+-])(\d*)$", name)
    if not m:
        return 0
    return (1 if m.group(1) == "+" else -1) * (int(m.group(2)) if m.group(2) else 1)


def surface_reactions(texts):
    """Parse SURFACE_SPECIES blocks; later definitions of the same surface species replace earlier ones."""
    rx = {}
    for txt in texts:
        in_block = False
        cur = None
        for raw in txt.splitlines():
            line = raw.split("#")[0].strip()
            if not line:
                continue
            if re.match(r"^[A-Z_]+$", line):
                in_block = line == "SURFACE_SPECIES"
                continue
            if not in_block:
                continue
            if "=" in line and "Hfo_" in line and not line.lower().startswith(("log_k", "-log_k")):
                lhs, rhs = line.split("=")
                L, Rr = split_side(lhs), split_side(rhs)
                site = [s for s, c in L if s.startswith("Hfo_")][0]
                prod = [s for s, c in Rr if s.startswith("Hfo_")][0]
                nu = {}
                for s, c in L:
                    if not s.startswith("Hfo_") and s != "H2O":
                        nu[s] = nu.get(s, 0) + c
                for s, c in Rr:
                    if not s.startswith("Hfo_") and s not in ("H2O",):
                        nu[s] = nu.get(s, 0) - c
                cur = dict(site=site, species=prod, nu=nu, z=charge_of(prod), log_k=None)
                rx[prod] = cur
            elif re.match(r"^-?log_k", line, flags=re.I) and cur is not None:
                cur["log_k"] = float(line.split()[1])
    return [r for r in rx.values() if r["species"] not in ("Hfo_wOH", "Hfo_sOH")]


def element_stoich(species_nu):
    """Element content of a surface species from its aqueous reactants (positive coefficients only)."""
    el = {}
    for s, c in species_nu.items():
        if c <= 0 or s == "H+":
            continue
        m = re.match(r"^(?:H\d*)?([A-Z][a-z]?)", s.replace("(OH)", ""))
        sym = {"PO4-3": "P", "CO3-2": "C", "SO4-2": "S", "MoO4-2": "Mo", "H3AsO4": "As", "H3AsO3": "As",
               "VO2+": "V", "HSeO3-": "Se", "SeO4-2": "Se", "CrO4-2": "Cr", "H3BO3": "B"}.get(s, m.group(1) if m else s)
        el[sym] = el.get(sym, 0) + c
    return el


# ----------------------------------------------------------------------------- independent DLM solver
def solve_surface(reactions, act, mu, t_c, S_w, S_s, area_m2):
    T = t_c + 273.15
    f = F / (R * T)
    pre = np.sqrt(8000.0 * eps_r(t_c) * EPS0 * R * T * mu)
    usable = [r for r in reactions if all(sp in act for sp in r["nu"])]

    def species(psi):
        base = {}
        for r in usable:
            lk = r["log_k"] * np.log(10)
            lk += sum(c * np.log(act[sp]) if act[sp] > 0 else -np.inf for sp, c in r["nu"].items())
            base[r["species"]] = (r, np.exp(lk - r["z"] * f * psi) if np.isfinite(lk) else 0.0)
        sums = {"Hfo_w": 0.0, "Hfo_s": 0.0}
        for name, (r, v) in base.items():
            sums[r["site"][:5]] += v
        x = {"Hfo_w": S_w / (1 + sums["Hfo_w"]), "Hfo_s": S_s / (1 + sums["Hfo_s"])}
        return {name: (r, v * x[r["site"][:5]]) for name, (r, v) in base.items()}, x

    def g(psi):
        sp, _ = species(psi)
        q = sum(r["z"] * n for r, n in sp.values())
        return F * q / area_m2 - pre * np.sinh(f * psi / 2.0)

    psi = brentq(g, -0.6, 0.6, xtol=1e-12)
    sp, x = species(psi)
    return psi, sp


# ----------------------------------------------------------------------------- PHREEQC runs
def run_single(sorbate, total_molal, phs, database_text_extra=""):
    """Single-sorbate edge in 0.1 M NaNO3 with 1e-3 M Fe as HFO at 25 C."""
    master = {"Cd": ("Cd", "Cd+2"), "P": ("P", "PO4-3")}[sorbate]
    reactants = ["H+", master[1]]
    heads = ["pH", "mu", "psi", "sigma_eq", "surf", "diss", "mass_w"] + [f"a_{s}" for s in reactants]
    punch = ['-LA("H+")', "MU", 'EDL("psi","Hfo")', 'EDL("charge","Hfo")', f'SURF("{master[0]}","Hfo")',
             f'TOT("{master[0]}")', 'TOT("water")'] + [f'ACT("{s}")' for s in reactants]
    txt = M.PHASES_FIX
    txt += ("SELECTED_OUTPUT\n -reset false\nUSER_PUNCH\n -headings " + " ".join(heads) + "\n -start\n" +
            "\n".join(f" {10 * (i + 1)} PUNCH {p}" for i, p in enumerate(punch)) + "\n -end\nEND\n")
    txt += f"SOLUTION 1\n -temp 25\n -units mol/kgw\n pH 7\n Na 0.1 charge\n N(5) 0.1\n {master[0]} {total_molal}\nEND\n"
    txt += "SURFACE 1\n Hfo_wOH 2e-4 600 0.089\n Hfo_sOH 5e-6\nEND\n"
    for ph in phs:
        reag = "NaOH" if ph >= 7 else "HNO3"
        txt += f"USE solution 1\nUSE surface 1\nEQUILIBRIUM_PHASES 1\n Fix_H+ {-ph:.3f} {reag} 10\nEND\n"
    eng = Engine(db_path("minteq.v4.dat"), "386")
    rows = [r for r in eng.run(M.REDOX_FIX_MINTEQV4 + M.SURF_MN + txt) if "psi" in r and r["psi"] != 0]
    return rows, reactants


def compare_single(sorbate, total, reactions):
    phs = np.round(np.arange(4.0, 10.0001, 0.25), 3)
    rows, reactants = run_single(sorbate, total, phs)
    out = []
    el = "Cd" if sorbate == "Cd" else "P"
    for r in rows:
        act = {s: r[f"a_{s}"] for s in reactants}
        psi, sp = solve_surface(reactions, act, r["mu"], 25.0, 2e-4, 5e-6, 600 * 0.089)
        sorbed = sum(n * element_stoich(rx["nu"]).get(el, 0) for rx, n in sp.values())
        out.append(dict(case=f"T{1 if el == 'Cd' else 2}_{el}_single_0.1M_NaNO3_1e-3M_Fe_25C", pH=r["pH"],
                        element=el, quantity="sorbed_mol", phreeqc=r["surf"], independent=sorbed))
        out.append(dict(case=out[-1]["case"], pH=r["pH"], element="-", quantity="psi_V", phreeqc=r["psi"],
                        independent=psi))
        out.append(dict(case=out[-1]["case"], pH=r["pH"], element=el, quantity="fraction_sorbed",
                        phreeqc=r["surf"] / (r["surf"] + r["diss"] * r["mass_w"]),
                        independent=sorbed / (sorbed + r["diss"] * r["mass_w"])))
    return out


def compare_production(reactions, model="DLM_HFO_minteqv4+CO3", water="soft", fe=1.0):
    """Rebuild the production input (same blocks as 03_run_hfo_model) with a punch of activities, then re-solve."""
    aq = sorted({s for r in reactions for s in r["nu"]})
    eng = Engine(db_path("minteq.v4.dat"), "386")
    ph_grid = np.round(np.arange(6.0, 9.0001, 0.25), 3)
    heads = ["mu", "psi", "mass_w"] + [f"a_{s}" for s in aq] + [f"S_{e}" for e in M.TRACES]
    exprs = ["MU", 'EDL("psi","Hfo")', 'TOT("water")'] + [f'ACT("{s}")' for s in aq] + \
            [f'SURF("{e}","Hfo")' for e in M.TRACES]
    txt = M.REDOX_FIX_MINTEQV4 + M.SURF_MN + (M.SURF_CO3 if model.endswith("+CO3") else "") + M.PHASES_FIX
    txt += ("SELECTED_OUTPUT\n -reset false\n -state true\nUSER_PUNCH\n -headings " + " ".join(heads) +
            "\n -start\n" + "\n".join(f" {10 * (i + 1)} PUNCH {p}" for i, p in enumerate(exprs)) + "\n -end\nEND\n")
    txt += run_hfo.solution_block(water) + run_hfo.surface_block(fe)
    for ph in ph_grid:
        txt += f"USE solution 1\nUSE surface 1\nEQUILIBRIUM_PHASES 1\n   Fix_H+ {-ph:.4f} CO2(g) 10.0\nEND\n"
    rows = [r for r in eng.run(txt) if str(r.get("state", "")).strip() == "react"]
    assert len(rows) == len(ph_grid)
    a = M.hfo_amounts(fe)
    out = []
    case = f"T3_production_{model}_{water}_HFO{fe:g}mgFeL_16C"
    for r, ph in zip(rows, ph_grid):
        act = {s: r[f"a_{s}"] for s in aq}
        psi, sp = solve_surface(reactions, act, r["mu"], M.TEMP_C, a["weak"], a["strong"],
                                a["g_hfo"] * M.HFO_AREA_M2_G)
        out.append(dict(case=case, pH=ph, element="-", quantity="psi_V", phreeqc=r["psi"], independent=psi))
        for e in M.TRACES:
            sorbed = sum(n * element_stoich(rx["nu"]).get(e, 0) for rx, n in sp.values())
            out.append(dict(case=case, pH=ph, element=e, quantity="sorbed_mol", phreeqc=r[f"S_{e}"],
                            independent=sorbed))
    return out


def ph50(df, case, el):
    g = df[(df.case == case) & (df.element == el) & (df.quantity == "fraction_sorbed")].sort_values("pH")
    fs = g.phreeqc.values
    x = g.pH.values
    if el == "P":   # anion: sorption falls with pH
        return float(np.interp(0.5, fs[::-1], x[::-1]))
    return float(np.interp(0.5, fs, x))


def standard_edges():
    """Diagnostic (PHREEQC only): single-sorbate edges under Dzombak & Morel's standard laboratory conditions
    (0.1 M NaNO3, 1e-3 M Fe as HFO = 0.089 g/L, 25 C, no CO2), sorbate 1e-7 M (cations) or 1e-6 M (oxyanions).
    Returns pH50 (pH of 50 % sorbed) and the local slope d log10(dissolved fraction)/d pH at pH 7."""
    names = dict(M.TRACES)
    res = []
    phs = np.round(np.arange(3.0, 11.0001, 0.05), 3)
    for el, (pname, _) in names.items():
        tot = 1e-7 if el in M.CATIONS else 1e-6
        txt = M.REDOX_FIX_MINTEQV4 + M.SURF_MN + M.PHASES_FIX
        txt += ("SELECTED_OUTPUT\n -reset false\n -state true\nUSER_PUNCH\n -headings pH surf diss mass_w\n -start\n"
                f' 10 PUNCH -LA("H+"), SURF("{el}","Hfo"), TOT("{el}"), TOT("water")\n -end\nEND\n')
        txt += f"SOLUTION 1\n -temp 25\n -units mol/kgw\n pH 7\n pe 8\n Na 0.1 charge\n N(5) 0.1\n {pname} {tot}\nEND\n"
        txt += "SURFACE 1\n Hfo_wOH 2e-4 600 0.089\n Hfo_sOH 5e-6\nEND\n"
        for ph in phs:
            reag = "NaOH" if ph >= 7 else "HNO3"
            txt += f"USE solution 1\nUSE surface 1\nEQUILIBRIUM_PHASES 1\n Fix_H+ {-ph:.3f} {reag} 10\nEND\n"
        eng = Engine(db_path("minteq.v4.dat"), "386")
        rows = [r for r in eng.run(txt) if str(r.get("state", "")).strip() == "react"]
        x = np.array([r["pH"] for r in rows])
        fs = np.array([r["surf"] / (r["surf"] + r["diss"] * r["mass_w"]) for r in rows])
        fd = 1 - fs
        if el in M.CATIONS:
            p50 = float(np.interp(0.5, fs, x)) if fs.max() > 0.5 and fs.min() < 0.5 else np.nan
        else:
            p50 = float(np.interp(0.5, fs[::-1], x[::-1])) if fs.max() > 0.5 and fs.min() < 0.5 else np.nan
        ly = np.log10(np.clip(fd, 1e-30, None))
        i7 = int(np.argmin(abs(x - 7.0)))
        slope7 = float(np.gradient(ly, x)[i7])
        res.append(dict(element=el, total_M=tot, pH50=round(p50, 2) if np.isfinite(p50) else np.nan,
                        max_fraction_sorbed=round(float(fs.max()), 4), pH_at_max=float(x[int(np.argmax(fs))]),
                        dissolved_fraction_pH7=round(float(fd[i7]), 4),
                        local_slope_log10_dissolved_fraction_pH7=round(slope7, 3)))
    df = pd.DataFrame(res)
    df.to_csv(os.path.join(ROOT, "validation", "dm_standard_conditions_edges.csv"), index=False)
    print(df.to_string(index=False))
    return df


def main():
    db_text = open(db_path("minteq.v4.dat"), encoding="latin-1").read()
    reactions = surface_reactions([db_text, M.SURF_MN, M.SURF_CO3])
    rows = []
    rows += compare_single("Cd", 1e-7, reactions)
    rows += compare_single("P", 1e-5, reactions)
    rows += compare_production(reactions, "DLM_HFO_minteqv4+CO3", "soft", 1.0)
    rows += compare_production(reactions, "DLM_HFO_minteqv4+CO3", "hard", 0.1)
    df = pd.DataFrame(rows)
    df["rel_diff"] = np.where(df.quantity == "psi_V", (df.independent - df.phreeqc),
                              df.independent / df.phreeqc.where(df.phreeqc != 0) - 1)
    df.to_csv(OUT, index=False)
    for (case, q), g in df.groupby(["case", "quantity"]):
        d = g.rel_diff.abs()
        lab = "max |abs diff| (V)" if q == "psi_V" else "max |rel diff|"
        # ignore elements present at < 1e-15 mol sorbed (round-off of 5-digit output)
        if q == "sorbed_mol":
            d = d[g.phreeqc.abs() > 1e-15]
        print(f"{case:62s} {q:16s} {lab} = {d.max():.2e}  (n={len(d)})")
    for case, el in [("T1_Cd_single_0.1M_NaNO3_1e-3M_Fe_25C", "Cd"), ("T2_P_single_0.1M_NaNO3_1e-3M_Fe_25C", "P")]:
        print(f"pH50 {el}: {ph50(df, case, el):.2f}")
    print("\nDiagnostic single-sorbate edges, D&M standard conditions (PHREEQC, minteq.v4 constants):")
    standard_edges()


if __name__ == "__main__":
    main()
